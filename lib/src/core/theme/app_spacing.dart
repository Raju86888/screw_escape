/// Design system spacing and layout dimension tokens.
abstract final class AppSpacing {
  /// Extra-small spacing: 4.0dp
  static const double xs = 4.0;

  /// Small spacing: 8.0dp
  static const double sm = 8.0;

  /// Medium spacing: 16.0dp
  static const double md = 16.0;

  /// Large spacing: 24.0dp
  static const double lg = 24.0;

  /// Extra-large spacing: 32.0dp
  static const double xl = 32.0;

  /// Double extra-large spacing: 48.0dp
  static const double xxl = 48.0;

  /// Standard border radius for small components (screws, badges): 4.0dp
  static const double radiusSm = 4.0;

  /// Standard border radius for buttons and cards: 12.0dp
  static const double radiusMd = 12.0;

  /// Large border radius for dialogs and modals: 20.0dp
  static const double radiusLg = 20.0;
}

